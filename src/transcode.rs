use std::collections::HashMap;

pub fn transcode(s: &str) -> String {
    let map: HashMap<char, &str> = [
        ('!', "%2521"),
        ('"', "%2522"),
        ('#', "%2523"),
        ('$', "%2524"),
        ('%', "%2525"),
        ('&', "%2526"),
        ('\'', "%2527"),
        ('(', "%2528"),
        (')', "%2529"),
        ('*', "%252A"),
        ('+', "%252B"),
        (',', "%252C"),
        ('/', "%252F"),
        (':', "%253A"),
        (';', "%253B"),
        ('<', "%253C"),
        ('=', "%253D"),
        ('>', "%253E"),
        ('?', "%253F"),
        ('@', "%2540"),
        ('[', "%255B"),
        ('\\', "%255C"),
        (']', "%255D"),
        ('^', "%255E"),
        ('_', "%255F"),
        ('`', "%2560"),
    ]
    .iter()
    .cloned()
    .collect();

    s.chars()
        .map(|c| {
            map.get(&c)
                .unwrap_or(&c.to_string().as_str())
                .to_string()
        })
        .collect()
}
